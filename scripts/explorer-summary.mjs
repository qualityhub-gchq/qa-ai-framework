#!/usr/bin/env node
/**
 * AI Explorer — final step: turn Playwright's results.json into the Pull Request description.
 * Usage: node scripts/explorer-summary.mjs <results.json> <output.md>
 * Reads env: EXPLORER_URL, EXPLORER_REQUIREMENTS, RUN_URL, LINT_OUTCOME, PLAN_FILE, TESTS_DIR
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const [resultsPath = 'test-results/results.json', outPath = 'pr-body.md'] = process.argv.slice(2);
const env = process.env;

/** Walk Playwright's nested suites and collect every test with its final status. */
function collectTests(suites, acc = []) {
  for (const suite of suites ?? []) {
    for (const spec of suite.specs ?? []) {
      for (const t of spec.tests ?? []) {
        const last = t.results?.[t.results.length - 1];
        acc.push({
          title: spec.title,
          file: spec.file,
          status: t.status,
          error: last?.error?.message,
        });
      }
    }
    collectTests(suite.suites, acc);
  }
  return acc;
}

// Strips terminal color codes from Playwright error messages.
// eslint-disable-next-line no-control-regex
const ANSI = /\u001b\[[0-9;]*m/g;

const icon = { expected: '✅', unexpected: '❌', flaky: '⚠️', skipped: '⏭️' };
let resultsSection;

if (existsSync(resultsPath)) {
  const results = JSON.parse(readFileSync(resultsPath, 'utf8'));
  const s = results.stats ?? {};
  const tests = collectTests(results.suites);
  const rows = tests
    .map((t) => {
      const err = t.error ? ` — ${t.error.split('\n')[0].replace(ANSI, '').slice(0, 140)}` : '';
      return `| ${icon[t.status] ?? '❔'} | ${t.title} | \`${t.file}\`${err} |`;
    })
    .join('\n');
  resultsSection = [
    `**Passed:** ${s.expected ?? 0} · **Failed:** ${s.unexpected ?? 0} · **Flaky:** ${s.flaky ?? 0} · **Skipped/fixme:** ${s.skipped ?? 0}`,
    '',
    '| | Test | File / first error line |',
    '|---|---|---|',
    rows || '| | _No tests were found_ | |',
  ].join('\n');
} else {
  resultsSection =
    '_No results file found — the generated tests did not run. Check the workflow log._';
}

const body = `## 🤖 AI Explorer results

| | |
|---|---|
| **Target URL** | ${env.EXPLORER_URL ?? '—'} |
| **Requirements given** | ${env.EXPLORER_REQUIREMENTS?.trim() ? env.EXPLORER_REQUIREMENTS.trim().replace(/\n/g, ' ') : '_None — tests describe the CURRENT behaviour of the site (see oracle note below)_'} |
| **Test plan** | \`${env.PLAN_FILE ?? ''}\` |
| **Tests** | \`${env.TESTS_DIR ?? ''}\` |
| **Lint on generated code** | ${env.LINT_OUTCOME === 'success' ? '✅ passed' : '⚠️ issues — see workflow log'} |
| **Workflow run (report + traces)** | ${env.RUN_URL ?? '—'} |

### Test run
${resultsSection}

### ✅ Reviewer checklist (human QA)
- [ ] Test plan covers the important flows; remove duplicates, add missing negative/edge cases
- [ ] Each expected result is **correct** (not just what the site currently does)
- [ ] Locators are user-facing (\`getByRole\`, \`getByLabel\`, \`getByTestId\`), no hard waits
- [ ] \`test.fixme\` tests reviewed: real bug → open an issue; bad test → fix or delete
- [ ] Approved tests: add \`@regression\` tag and move into \`tests/ui/\` (refactor into Page Objects)

> **Oracle note:** AI can observe what a site *does*, not what it *should* do. Without requirements,
> a generated test may lock in an existing bug. Human review is mandatory before merging.

_Generated by the AI Explorer workflow. Nothing in this PR runs in the nightly regression until a human promotes it._
`;

writeFileSync(outPath, body);
console.log(body);
